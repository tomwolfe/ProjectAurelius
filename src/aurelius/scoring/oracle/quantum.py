def _count_aromatic_rings(mol: Chem.Mol) -> int:
    """Count number of aromatic rings (all atoms in ring are aromatic)."""
    ring_info = mol.GetRingInfo()
    n_aromatic = 0
    for ring in ring_info.AtomRings():
        if all(mol.GetAtomWithIdx(i).GetIsAromatic() for i in ring):
            n_aromatic += 1
    return n_aromatic


def _wiener_index(mol: Chem.Mol) -> float:
    """Compute the Wiener index (sum of all-pairs shortest path distances).

    Physical basis: The Wiener index measures molecular compactness. A lower
    Wiener index (more compact) correlates with stronger interatomic
    interactions and stabilised frontier orbitals. This is a closed-form
    topological descriptor — no regression weights needed.
    """
    n = mol.GetNumAtoms()
    if n <= 1:
        return 0.0
    total = 0
    from rdkit.Chem import rdmolops
    matrix = rdmolops.GetDistanceMatrix(mol)
    for i in range(n):
        for j in range(i + 1, n):
            total += int(matrix[i][j])
    return float(total)


def _apply_wiener_compactness(mol: Chem.Mol, L: int) -> int:
    """Adjust conjugation length L based on Wiener-index molecular compactness.

    Physical basis: Compact molecules (low Wiener index per atom) have stronger
    through-space orbital overlap, effectively shortening the conjugation path.
    L is reduced by up to 30% based on compactness = 1 - W/W_linear.
    """
    n_atoms = mol.GetNumAtoms()
    w = _wiener_index(mol)
    if n_atoms <= 1:
        return L
    w_linear = n_atoms * (n_atoms * n_atoms - 1) / 6.0
    if w_linear <= 0:
        return L
    compactness = max(0.0, 1.0 - w / w_linear)
    L = int(L * (1.0 - 0.30 * compactness))
    return max(L, 2)


def _conjugated_bond_deviation(
    mol: Chem.Mol, conf: Chem.Conformer, i: int, j: int
) -> float | None:
    """Measure the torsional deviation from planarity for a conjugated bond (i-j).

    Finds flanking conjugated neighbors on both sides of the bond and returns
    the minimum angular deviation from 0° or 180° (planar). Returns None if
    suitable flanking atoms cannot be found.
    """
    from rdkit.Chem import rdMolTransforms

    ai = mol.GetAtomWithIdx(i)
    aj = mol.GetAtomWithIdx(j)
    ni = None
    for nb in ai.GetNeighbors():
        n_idx = nb.GetIdx()
        if n_idx != j and _is_conjugated_bond(mol, i, n_idx):
            ni = n_idx
            break
    nj = None
    for nb in aj.GetNeighbors():
        n_idx = nb.GetIdx()
        if n_idx != i and _is_conjugated_bond(mol, j, n_idx):
            nj = n_idx
            break
    if ni is None or nj is None:
        return None
    try:
        dihedral = abs(rdMolTransforms.GetDihedralDeg(conf, ni, i, j, nj))
        return min(dihedral, abs(180.0 - dihedral))
    except Exception:
        return None


def _apply_torsional_strain_penalty(mol: Chem.Mol, L: int) -> int:
    """Reduce effective conjugation length L if conjugated system is non-planar.

    Physical basis: The particle-in-a-box model assumes a perfectly planar
    conjugated system. Torsional strain (dihedral > 30°) between adjacent
    conjugated atoms breaks pi-orbital overlap, effectively shortening the
    conjugation path. This prevents false-positive narrow gaps for sterically
    hindered conjugated molecules (e.g., bulky biphenyl derivatives).

    Uses RDKit's ETKDGv3 conformer generation with useRandomCoords and UFF
    relaxation (maxIts=500) to escape local minima for sterically hindered
    molecules. For each conjugated bond with flanking neighbors, the dihedral
    angle is measured. If any exceeds 30 deg, L is reduced by 30% (floor 2).
    """
    if L <= 2:
        return L
    from rdkit.Chem import AllChem

    mol_copy = Chem.RWMol(mol)
    mol_copy.UpdatePropertyCache()
    try:
        mol_copy = Chem.AddHs(mol_copy)
        params = AllChem.ETKDGv3()
        params.randomSeed = 42
        params.useRandomCoords = True
        result = AllChem.EmbedMolecule(mol_copy, params)
        if result != 0:
            return L
        AllChem.UFFOptimizeMolecule(mol_copy, maxIters=500)
        conf = mol_copy.GetConformer()
    except Exception:
        return L

    max_deviation = 0.0
    for bond in mol.GetBonds():
        if not bond.GetIsConjugated():
            continue
        deviation = _conjugated_bond_deviation(
            mol, conf, bond.GetBeginAtomIdx(), bond.GetEndAtomIdx()
        )
        if deviation is not None and deviation > max_deviation:
            max_deviation = deviation

    if max_deviation > 30.0:
        L = max(2, int(L * 0.7))
    return L


def _apply_peierls_damping(L: int) -> int:
    """Apply Peierls distortion damping to prevent 1/L² gap collapse for L > 8.

    Physical basis: Long polyenes undergo bond-length alternation that opens a
    finite gap (ΔE ≈ 1.5-2.0 eV) even for infinite chains. The closed-form
    saturation L_eff = 8 + (L-8)/(1+0.10·(L-8)) preserves moderate-L behavior.
    """
    if L <= 8:
        return L
    alpha = 0.10
    L = int(8 + (L - 8) / (1.0 + alpha * (L - 8)))
    return max(L, 2)


def _compute_tom_base_energies(L: int) -> tuple[float, float]:
    """Compute base HOMO/LUMO from conjugation length using particle-in-a-box.

    The gap scales as ΔE = 37.6 / L² (eV). For L < 3, uses fixed base values.
    Base offsets calibrated against orbital_calibration.json (45 references).
    """
    base_homo = -6.8
    base_lumo = 1.5
    if L >= 3:
        gap = 37.6 / (L * L)
        mid = (base_homo + base_lumo) / 2.0
        return mid - gap / 2.0, mid + gap / 2.0
    return base_homo, base_lumo


def _apply_heteroatom_perturbations(n_ew: int, n_ed: int, homo: float, lumo: float) -> tuple[float, float]:
    """Apply Hueckel-like heteroatom corrections to HOMO/LUMO.

    Electron-withdrawing groups stabilise both orbitals; electron-donating
    groups destabilise. EW coefficient -0.32, LUMO EW scaling 0.35 (HOMO-biased).
    """
    ew_shift = -0.32 * n_ew
    ed_shift = 0.12 * n_ed
    return homo + ew_shift + ed_shift, lumo + ew_shift * 0.35 + ed_shift * 0.5


def _apply_fluorine_correction(mol: Chem.Mol, homo: float, lumo: float) -> tuple[float, float]:
    """Apply fluorine inductive withdrawal correction (-0.15 eV per F)."""
    n_f = sum(a.GetAtomicNum() == 9 for a in mol.GetAtoms())
    f_shift = -0.15 * n_f
    return homo + f_shift, lumo + f_shift


def _apply_aromatic_stabilization(mol: Chem.Mol, homo: float, lumo: float) -> tuple[float, float]:
    """Apply aromatic ring stabilization (-0.25 HOMO, -0.15 LUMO per ring).

    Physical basis: Cyclic delocalisation (resonance energy ~1.5 eV for benzene)
    stabilises both frontier orbitals beyond 1-D PIB confinement.
    """
    n_arom = _count_aromatic_rings(mol)
    return homo + -0.25 * n_arom, lumo + -0.15 * n_arom


def _apply_nitrile_correction(mol: Chem.Mol, lumo: float) -> float:
    """Apply nitrile C≡N π* LUMO lowering (-0.70 eV per nitrile).

    Physical basis: The C≡N π* orbital is ~0.7-1.0 eV lower than the general
    N perturbation predicts.
    """
    n_nitrile = len(mol.GetSubstructMatches(NITRILE_PATTERN))
    return lumo + -0.70 * n_nitrile


def _apply_phosphate_correction(mol: Chem.Mol, homo: float) -> float:
    """Apply phosphate HOMO correction (+0.50 per P=O) for σ-only P-O-C bonds.

    Physical basis: σ-only P-O-C oxygen EW contributions are over-counted;
    +0.50 corrects ~2/3 of the over-counting (~0.96 eV for trialkyl phosphates).
    """
    n_phosphate = len(mol.GetSubstructMatches(_PHOSPHATE_PATTERN))
    return homo + 0.50 * n_phosphate


def _apply_sigma_star_correction(mol: Chem.Mol, L: int, lumo: float) -> float:
    """Apply σ* LUMO correction for non-conjugated S/P=O groups (d-orbital participation).

    Physical basis: S=O and P=O bonds have low-lying σ* orbitals from d-orbital
    participation that lower LUMO by 0.3-0.7 eV. Applied only for L<3 where the
    LUMO is σ* (not π*) character.
    """
    if L >= 3:
        return lumo
    for _spattern, _sname, _sshift in _SIGMA_STAR_LUMO:
        if len(mol.GetSubstructMatches(_spattern)) > 0:
            lumo += _sshift
    return lumo


def _apply_cross_conjugation_penalty(mol: Chem.Mol, lumo: float) -> float:
    """Apply cross-conjugation penalty (+0.30 eV to LUMO).

    Physical basis: Cross-conjugated systems disrupt pi-delocalisation; the
    1D particle-in-a-box overestimates the gap. Widening by +0.30 eV corrects
    for this overestimation (e.g., divinyl ketone, benzophenone).
    """
    if _is_cross_conjugated(mol):
        return lumo + 0.30
    return lumo


def predict_tom_orbitals(mol: Chem.Mol) -> tuple[float, float]:
    """Predict HOMO/LUMO using the Topological Orbital Model (TOM).

    The model estimates frontier orbital energies from:
        1. Longest conjugation path length (L)
        2. HOMO-LUMO gap from particle-in-a-box: ΔE ∝ 1/L²
        3. Heteroatom perturbations (electron-withdrawing/donating)
        4. Aromatic ring stabilization (−0.25 eV HOMO, −0.15 eV LUMO per ring)
        5. Wiener-index compactness adjustment (factor 0.30)
        6. σ* LUMO correction for S/P=O groups in non-conjugated molecules
        7. Phosphate HOMO correction (+0.50 per P=O) for σ-only P-O-C bonds
        8. Base offset calibrated to 45 electrolyte molecules from DFT references.
        9. Cross-conjugation penalty for branched pi-systems.

    Returns:
        (homo_eV, lumo_eV)
    """
    L = _longest_conjugation_path(mol)
    L = max(L, 2)
    L = _topological_sanity_l(mol, L)
    L = _apply_wiener_compactness(mol, L)
    L = _apply_torsional_strain_penalty(mol, L)
    L = _apply_peierls_damping(L)

    n_ew, n_ed, _ = _count_heteroatom_perturbations(mol)
    homo, lumo = _compute_tom_base_energies(L)
    homo, lumo = _apply_heteroatom_perturbations(n_ew, n_ed, homo, lumo)
    homo, lumo = _apply_fluorine_correction(mol, homo, lumo)
    homo, lumo = _apply_aromatic_stabilization(mol, homo, lumo)
    lumo = _apply_nitrile_correction(mol, lumo)
    homo = _apply_phosphate_correction(mol, homo)
    lumo = _apply_sigma_star_correction(mol, L, lumo)
    lumo = _apply_cross_conjugation_penalty(mol, lumo)

    return homo, lumo


# ---------------------------------------------------------------------------
# Domain of Applicability (DoA) — TOM-specific epistemic uncertainty
# ---------------------------------------------------------------------------
# Physical justification: The TOM is calibrated against molecules with moderate
# conjugation (L ≤ 12) and reasonable pi-electron counts. Molecules with extreme
# conjugation paths lacking sp3 structural support, or excessive pi-systems,
# fall outside the TOM calibration domain. The particle-in-a-box model assumes
# a planar rigid system; long conjugation without sp3 breaks planarity, and
# excessive pi-electrons violate the single-particle HMO approximation.
# These are closed-form heuristics — no ML involved.


def compute_quantum_domain_penalty(ctx: MoleculeContext) -> tuple[float, str]:
    """Compute domain-of-applicability penalty for TOM predictions.

    Penalises molecules with topological features that fall outside the
    TOM calibration domain (conjugation > 12 without sp3 support, excessive
    pi-electrons).

    Returns:
        (penalty_multiplier, reason_string)
        Multiplier in [0.70, 1.0]; 1.0 = fully within domain.
    """
    mol = ctx.mol
    reasons: list[str] = []
    penalty = 1.0

    L = _longest_conjugation_path(mol)
    if L > 12:
        n_c = sum(a.GetAtomicNum() == 6 for a in mol.GetAtoms())
        n_sp3 = sum(
            a.GetAtomicNum() == 6 and a.GetHybridization() == Chem.HybridizationType.SP3
            for a in mol.GetAtoms()
        )
        sp3_frac = n_sp3 / max(n_c, 1)
        if sp3_frac < 0.15:
            penalty *= 0.70
            reasons.append(
                f"long conjugation (L={L}) without sp3 support (sp3_frac={sp3_frac:.2f})"
            )

    _, _, n_pi = _count_heteroatom_perturbations(mol)
    if n_pi > 24:
        penalty *= 0.80
        reasons.append(f"excessive pi-system (n_pi={n_pi}) outside TOM calibration")

    return penalty, "; ".join(reasons) if reasons else "within domain"


# ---------------------------------------------------------------------------
# QuantumOracle — Unified interface for xTB + TOM fallback
# ---------------------------------------------------------------------------


class QuantumOracle:
    """Quantum-chemical oracle for frontier orbital energies.

    Two-tier evaluation:
       1. xTB (GFN2-xTB) via subprocess — preferred, real QM
       2. Topological Orbital Model (TOM) — conjugation-aware fallback

    When xTB is available, generates multiple conformers via ETKDGv3,
    UFF-optimises each, computes Boltzmann weights, and runs xTB on the
    top-3 lowest-energy conformers. The final HOMO/LUMO is the
    Boltzmann-weighted average, and ``quantum_confidence`` reports the
    conformer energy variance as a proxy for prediction stability.

    Results are cached by SMILES to avoid redundant computation.
    """

    def __init__(
        self,
        use_xtb: bool = True,
        n_conformers: int = _N_CONFORMERS,
        n_top_conformers: int = _N_TOP_CONFORMERS,
    ) -> None:
        self._use_xtb = use_xtb and _HAS_XTB
        self._n_conformers = n_conformers
        self._n_top_conformers = n_top_conformers
        self._cache: dict[str, dict[str, float]] = {}
        self._n_xtb_calls = 0
        self._n_tom_calls = 0

        if use_xtb and not _HAS_XTB:
            logger.info("QuantumOracle: xTB binary not found — using TOM fallback.")
        elif self._use_xtb:
            logger.info("QuantumOracle: xTB backend ENABLED.")

    @property
    def method(self) -> str:
        return "xTB (GFN2-xTB)" if self._use_xtb else "TOM (Topological Orbital Model)"

    @property
    def n_quantum_calls(self) -> int:
        return self._n_xtb_calls + self._n_tom_calls

    @staticmethod
    def _run_xtb_flat(conformers: list[tuple[str, float]], n_top: int) -> tuple[list[dict[str, float]], list[float]]:
        """Run xTB on top N conformers, return (results, energies)."""
        top = conformers[:n_top]
        results: list[dict[str, float]] = []
        energies: list[float] = []
        for xyz, uff_energy in top:
            xtb_result = _run_xtb(xyz)
            if xtb_result is not None:
                results.append(xtb_result)
                energies.append(uff_energy)
        return results, energies

    @staticmethod
    def _boltzmann_average(xtb_results: list[dict[str, float]], energies: list[float]) -> dict[str, float]:
        """Compute Boltzmann-weighted average HOMO/LUMO/dipole from xTB results."""
        weights = _boltzmann_weights(energies)
        homo_w = sum(w * r["homo_eV"] for w, r in zip(weights, xtb_results, strict=False))
        lumo_w = sum(w * r["lumo_eV"] for w, r in zip(weights, xtb_results, strict=False))
        dipole_w = sum(w * r.get("dipole_D", 0.0) for w, r in zip(weights, xtb_results, strict=False))
        homo_vals = [r["homo_eV"] for r in xtb_results]
        conformer_variance = float(np.std(homo_vals, ddof=1)) if len(homo_vals) > 1 else 0.0
        conf = "xtb_high" if conformer_variance < 0.15 else "xtb"
        return {
            "homo_eV": homo_w,
            "lumo_eV": lumo_w,
            "dipole_D": dipole_w,
            "conformer_variance": round(conformer_variance, 4),
            "quantum_confidence": conf,
        }

    def _evaluate_with_boltzmann(self, mol: Chem.Mol) -> dict[str, float]:
        """Evaluate using Boltzmann-weighted multi-conformer averaging.

        Generates up to N conformers, runs xTB on the top-3 lowest UFF
        energy conformers, and computes Boltzmann-weighted average
        HOMO/LUMO. Returns a quantum_confidence metric based on the
        standard deviation of HOMO across conformers.
        """
        conformers = _generate_multi_xyz(mol, n_conformers=self._n_conformers)
        if not conformers:
            result = _run_xtb(_generate_xyz(mol))
            if result is not None:
                self._n_xtb_calls += 1
                result["quantum_confidence"] = "xtb"
                return result
            return self._evaluate_tom(mol)

        xtb_results, energies = self._run_xtb_flat(conformers, self._n_top_conformers)

        if not xtb_results:
            self._n_xtb_calls += 1
            result = _run_xtb(conformers[0][0])
            if result is not None:
                self._n_xtb_calls += 1
                result["quantum_confidence"] = "xtb"
                return result
            return self._evaluate_tom(mol)

        self._n_xtb_calls += len(xtb_results)

        if len(xtb_results) == 1:
            result = dict(xtb_results[0])
            result["quantum_confidence"] = "xtb"
            return result

        return self._boltzmann_average(xtb_results, energies)

    def _evaluate_tom(self, mol: Chem.Mol) -> dict[str, float]:
        """Fallback TOM evaluation."""
        homo, lumo = predict_tom_orbitals(mol)
        L = _longest_conjugation_path(mol)
        n_rings = mol.GetRingInfo().NumRings()
        conf_var = 0.0
        result: dict[str, float] = {
            "homo_eV": homo,
            "lumo_eV": lumo,
            "dipole_D": 0.0,
            "conformer_variance": conf_var,
            "quantum_confidence": "tom_high" if L <= 8 and n_rings <= 2 else "tom_low",
        }
        return result

    def evaluate(self, mol: Chem.Mol) -> dict[str, float]:
        smiles = Chem.MolToSmiles(mol)
        if smiles in self._cache:
            return dict(self._cache[smiles])

        if self._use_xtb:
            result = self._evaluate_with_boltzmann(mol)
            if result is not None and "conformer_variance" in result:
                self._cache[smiles] = result
                return dict(result)
            logger.warning("QuantumOracle: xTB calculation failed — falling back to TOM.")

        result = self._evaluate_tom(mol)
        self._n_tom_calls += 1
        self._cache[smiles] = result
        return dict(result)

    def clear_cache(self) -> None:
        self._cache.clear()

    def get_cache_size(self) -> int:
        return len(self._cache)
