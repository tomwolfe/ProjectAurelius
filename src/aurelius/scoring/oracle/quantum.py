    """Remove the shared xTB temp workspace on interpreter exit."""
    global _XTB_BASE_TEMP
    if _XTB_BASE_TEMP is not None and os.path.exists(_XTB_BASE_TEMP):
        shutil.rmtree(_XTB_BASE_TEMP, ignore_errors=True)
        _XTB_BASE_TEMP = None


