_N_CONFORMERS: int = 5
_N_TOP_CONFORMERS: int = 3
_BOLTZMANN_TEMP: float = 298.15
_R_GAS: float = 0.001987  # kcal/(mol*K)


def _generate_xyz(mol: Chem.Mol) -> str:
    """Generate an XYZ string from a molecule with a 3D conformer."""
    from rdkit.Chem import AllChem

    mol = Chem.RWMol(mol)
    mol.UpdatePropertyCache()
    with contextlib.suppress(Exception):
        mol = Chem.AddHs(mol)

    params = AllChem.ETKDGv3()
    params.randomSeed = 42
    result = AllChem.EmbedMolecule(mol, params)
    if result != 0:
        return _generate_xyz_geometry_optimized(mol)

    with contextlib.suppress(Exception):
        AllChem.UFFOptimizeMolecule(mol, maxIters=250)

    conf = mol.GetConformer()
    n_atoms = mol.GetNumAtoms()
    lines = [str(n_atoms), ""]
    for i in range(n_atoms):
        atom = mol.GetAtomWithIdx(i)
        symb = atom.GetSymbol()
        pos = conf.GetAtomPosition(i)
        lines.append(f"{symb} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}")
    return "\n".join(lines)


def _generate_multi_xyz(
    mol: Chem.Mol,
    n_conformers: int = _N_CONFORMERS,
    random_seed: int = 42,
) -> list[tuple[str, float]]:
    """Generate multiple conformers with UFF optimizations and energies.

    Uses ETKDGv3 with multiple random seeds to sample diverse conformer
    space. Each conformer is UFF-optimized and its UFF energy is returned.

    Physical justification: A single conformer generated by ETKDGv3 can
    be a high-energy, non-physical geometry that leads to garbage xTB/TOM
    predictions. Boltzmann weighting over multiple conformers stabilises
    predictions by down-weighting high-energy conformers and avoiding
    false-positive narrow gaps from strained geometries. This is especially
    important for flexible electrolyte molecules (e.g., glymes, long-chain
    carbonates) that have many accessible conformations in solution.

    Returns:
        List of (xyz_string, uff_energy_kcal) tuples, sorted by energy
        ascending (lowest energy first).
    """
    from rdkit.Chem import AllChem

    mol = Chem.RWMol(mol)
    mol.UpdatePropertyCache()
    with contextlib.suppress(Exception):
        mol = Chem.AddHs(mol)

    results: list[tuple[str, float]] = []

    for i in range(n_conformers):
        mol_copy = Chem.RWMol(mol)
        params = AllChem.ETKDGv3()
        params.randomSeed = random_seed + i * 7
        result = AllChem.EmbedMolecule(mol_copy, params)
        if result != 0:
            continue
        try:
            ff = AllChem.UFFGetMoleculeForceField(mol_copy)
            if ff is None:
                continue
            converged = ff.Minimize(maxIts=500)
            energy = ff.CalcEnergy()
        except Exception:
            continue

        conf = mol_copy.GetConformer()
        n_atoms = mol_copy.GetNumAtoms()
        lines = [str(n_atoms), ""]
        for j in range(n_atoms):
            atom = mol_copy.GetAtomWithIdx(j)
            symb = atom.GetSymbol()
            pos = conf.GetAtomPosition(j)
            lines.append(f"{symb} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}")
        xyz = "\n".join(lines)
        results.append((xyz, energy))

    results.sort(key=lambda x: x[1])
    return results


def _boltzmann_weights(
    energies: list[float],
    temperature: float = _BOLTZMANN_TEMP,
) -> list[float]:
    """Compute Boltzmann weights from UFF energies.

    Physical justification: The Boltzmann factor exp(-E/kT) gives the
    relative probability of each conformer at temperature T. Conformers
    with energy > 5 kcal/mol above the minimum have negligible weight
    (< 0.02% at 298K) and are effectively excluded.

    Args:
        energies: List of UFF energies in kcal/mol.
        temperature: Temperature in Kelvin (default 298.15 K).

    Returns:
        List of normalised Boltzmann weights summing to 1.0.
    """
    if not energies:
        return []
    e_min = min(energies)
    boltz = [
        math.exp(-(e - e_min) / (_R_GAS * temperature))
        for e in energies
    ]
    total = sum(boltz)
    if total <= 0.0:
        return [1.0 / len(energies)] * len(energies)
    return [w / total for w in boltz]


def _generate_xyz_geometry_optimized(mol: Chem.RWMol) -> str:
    """Fallback XYZ generation using distance geometry without ETKDG."""
    from rdkit.Chem import AllChem, rdDistGeom

    mol = Chem.RWMol(mol)
    mol.UpdatePropertyCache()
    with contextlib.suppress(Exception):
        mol = Chem.AddHs(mol)

    params = rdDistGeom.ETKDGv3()
    params.randomSeed = 42  # type: ignore[assignment]
    params.useRandomCoords = True  # type: ignore[assignment]
    result = AllChem.EmbedMolecule(mol, params)
    if result != 0:
        with contextlib.suppress(Exception):
            AllChem.EmbedMolecule(mol, rdDistGeom.ETKDGv3())

    with contextlib.suppress(Exception):
        AllChem.UFFOptimizeMolecule(mol, maxIters=200)

    conf = mol.GetConformer()
    n_atoms = mol.GetNumAtoms()
    lines = [str(n_atoms), ""]
    for i in range(n_atoms):
        atom = mol.GetAtomWithIdx(i)
        symb = atom.GetSymbol()
        pos = conf.GetAtomPosition(i)
        lines.append(f"{symb} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}")
    return "\n".join(lines)


def _run_xtb(xyz_content: str, workdir: str | None = None) -> dict[str, float] | None:
    """Run xTB single-point calculation and parse HOMO/LUMO from output.

    Uses the module-level cached binary path and shared temp workspace
    to avoid per-call binary discovery and repeated temp dir creation.
    """
    if _XTB_BIN is None:
        return None
    if workdir is None:
        base = _XTB_BASE_TEMP or tempfile.gettempdir()
        workdir = tempfile.mkdtemp(dir=base, prefix="mol_")

    xyz_path = os.path.join(workdir, "input.xyz")
    with open(xyz_path, "w") as f:
        f.write(xyz_content)

    try:
        result = subprocess.run(
            [_XTB_BIN, "--gfn", "2", "--sp", xyz_path],
            cwd=workdir,
            capture_output=True, text=True, timeout=120,
        )
        return _parse_xtb_output(result.stdout)
    except (subprocess.TimeoutExpired, subprocess.CalledProcessError, OSError) as exc:
        logger.debug("xTB run failed: %s", exc)
        return None


def run_xtb_batch(
    xyz_list: list[str], max_workers: int = 4
) -> list[dict[str, float] | None]:
    """Run multiple xTB single-point calculations in parallel.

    Uses a ThreadPoolExecutor to overlap subprocess I/O. Subprocess calls
    release the GIL, so threading is effective for xTB batch execution
    without the overhead of process pool serialization.

    Args:
        xyz_list: List of XYZ-format molecular geometry strings.
        max_workers: Maximum parallel xTB processes (default 4).

    Returns:
        List of result dicts in the same order as xyz_list. Each entry is
        None if xTB failed or is unavailable.
    """
    if _XTB_BIN is None:
        return [None] * len(xyz_list)

    base = _XTB_BASE_TEMP or tempfile.gettempdir()
    workdirs = [
        tempfile.mkdtemp(dir=base, prefix=f"batch_{i}_")
        for i in range(len(xyz_list))
    ]

    results: list[dict[str, float] | None] = [None] * len(xyz_list)
    with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as pool:
        future_map: dict[concurrent.futures.Future[dict[str, float] | None], int] = {
            pool.submit(_run_xtb, xyz, wd): i
            for i, (xyz, wd) in enumerate(zip(xyz_list, workdirs))
        }
        for future in concurrent.futures.as_completed(future_map):
            idx = future_map[future]
            try:
                results[idx] = future.result()
            except Exception as exc:
                logger.debug("xTB batch item %d failed: %s", idx, exc)
                results[idx] = None

    return results


_XTB_HOMO_RE = re.compile(r"HOMO\s*:\s*([-+]?\d+\.?\d*)\s*eV")
_XTB_LUMO_RE = re.compile(r"LUMO\s*:\s*([-+]?\d+\.?\d*)\s*eV")


def _parse_xtb_output(output: str) -> dict[str, float] | None:
    """Parse xTB output text for HOMO, LUMO, and dipole moment."""
    homo_match = _XTB_HOMO_RE.search(output)
    lumo_match = _XTB_LUMO_RE.search(output)

    if homo_match and lumo_match:
        homo = float(homo_match.group(1))
        lumo = float(lumo_match.group(1))
        logger.info("QuantumOracle (xTB): HOMO=%.3f eV, LUMO=%.3f eV", homo, lumo)
        return {
            "homo_eV": homo,
            "lumo_eV": lumo,
            "dipole_D": 0.0,
        }

    logger.debug("Could not parse HOMO/LUMO from xTB output")
    return None


# ---------------------------------------------------------------------------
# Topological Orbital Model (TOM) — Non-linear Fallback for HOMO/LUMO
# ---------------------------------------------------------------------------
# Based on Hueckel Molecular Orbital (HMO) theory and the particle-in-a-box:
#   - The pi-electron system defines the frontier orbital energy scale
#   - Conjugation length L determines the HOMO-LUMO gap: DeltaE ∝ 1/L²
#   - Heteroatoms perturb the energy via electronegativity differences
#   - The model is non-linear in molecular topology (not fragment-additive)


def _longest_conjugation_path(mol: Chem.Mol) -> int:
    """Find the longest conjugated pi-system in a molecule.

    Returns the number of conjugated atoms in the longest continuous
    conjugated path.
    """
    visited: set[int] = set()
    max_path = 0

    def _dfs(atom_idx: int, path_len: int) -> None:
        nonlocal max_path
        visited.add(atom_idx)
        max_path = max(max_path, path_len)
        atom = mol.GetAtomWithIdx(atom_idx)
        for neighbor in atom.GetNeighbors():
            n_idx = neighbor.GetIdx()
            if n_idx not in visited and _is_conjugated_bond(mol, atom_idx, n_idx):
                _dfs(n_idx, path_len + 1)
        visited.discard(atom_idx)

    for atom in mol.GetAtoms():
        if atom.GetIsAromatic() or atom.GetDegree() > 0:
            _dfs(atom.GetIdx(), 1)

    return max_path


def _is_conjugated_bond(mol: Chem.Mol, i: int, j: int) -> bool:
    """Check if bond between atoms i and j is conjugated."""
    bond = mol.GetBondBetweenAtoms(i, j)
    if bond is None:
        return False
    if bond.GetIsConjugated():
        return True
    bond_type = bond.GetBondType()
    if bond_type in (Chem.BondType.DOUBLE, Chem.BondType.TRIPLE, Chem.BondType.AROMATIC):
        return True
    a1 = mol.GetAtomWithIdx(i)
    a2 = mol.GetAtomWithIdx(j)
    return bool(a1.GetIsAromatic() or a2.GetIsAromatic())


def _is_cross_conjugated(mol: Chem.Mol) -> bool:
    """Check if molecule contains a cross-conjugated pi system.

    Physical basis: Cross-conjugation occurs when a conjugated atom has >2
    conjugated neighbors with at least 2 of those being non-oxygen (carbon)
    conjugated substituents. This excludes normal resonance in esters and
    carbonates (O-C(=O)-O) where oxygen lone-pair donation creates partial
    double-bond character but does NOT disrupt linear pi-delocalisation.
    True cross-conjugation (e.g., divinyl ketone C=CC(=O)C=C, benzophenone
    O=C(c1ccccc1)c1ccccc1) branches the pi system, which the 1D
    particle-in-a-box model overestimates.

    Returns:
        True if any atom has >2 conjugated neighbors with >=2 non-oxygen.
    """
    for atom in mol.GetAtoms():
        n_conj = 0
        n_conj_carbon = 0
        for nb in atom.GetNeighbors():
            if _is_conjugated_bond(mol, atom.GetIdx(), nb.GetIdx()):
                n_conj += 1
                if nb.GetAtomicNum() == 6:
                    n_conj_carbon += 1
        if n_conj > 2 and n_conj_carbon >= 2:
            return True
    return False


# Heteroatom perturbation parameters for the Topological Orbital Model (TOM).
# Each entry: (atomic_num, pi_electrons, ew_flag, ed_flag, is_aromatic_ed)
_ATOM_PERTURBATIONS: list[tuple[int, int, int, int, bool]] = [
    (6, 1, 0, 0, False),    # aromatic carbon
    (7, 1, 1, 0, False),    # non-aromatic N (EW)
    (7, 1, 0, 1, True),     # aromatic N (ED)
    (8, 2, 1, 0, False),    # oxygen
    (9, 0, 1, 0, False),    # fluorine
    (16, 2, 1, 0, False),   # sulfur
    (15, 1, 1, 0, False),   # phosphorus
]


def _count_heteroatom_perturbations(mol: Chem.Mol) -> tuple[int, int, int]:
    """Count electron-withdrawing (EW) and electron-donating (ED) heteroatoms
    in conjugated positions, and total pi-electrons.

    Uses a data-driven lookup table for heteroatom perturbation parameters
    instead of a long if/elif chain.

    Returns:
        (n_ew, n_ed, n_pi_electrons)
    """
    n_ew = 0
    n_ed = 0
    n_pi = 0

    for atom in mol.GetAtoms():
        z = atom.GetAtomicNum()
        if not (atom.GetIsAromatic() or atom.GetDegree() > 0):
            continue
        for az, pi, ew, ed, aromatic_ed in _ATOM_PERTURBATIONS:
            if z != az:
                continue
            if aromatic_ed:
                if atom.GetIsAromatic():
                    n_ed += ed
                else:
                    n_ew += 1
            else:
                n_ew += ew
                n_ed += ed
            n_pi += pi
            break

    return n_ew, n_ed, n_pi


def _topological_sanity_l(mol: Chem.Mol, L: int) -> int:
    """Cap effective conjugation length if the molecule lacks 3D structural support.

    Physical justification: The particle-in-a-box gap (ΔE ∝ 1/L²) assumes a
    perfectly planar, rigid conjugated system. Real molecules with long
    conjugation paths (L > 12) require structural support — sp3 carbons,
    branching, or ring fusion — to maintain planarity against torsional
    disorder. A molecule with a long linear polyene chain but negligible sp3
    character (sp3 fraction < 0.10) will have severe torsional disorder that
    breaks conjugation, making the 1/L² gap scaling invalid. The effective
    conjugation length is capped at 12 in such cases, which corresponds to
    a gap floor of ~0.26 eV — realistically the minimum gap for any organic
    electrolyte molecule in solution.
    """
    if L <= 12:
        return L
    n_c = sum(a.GetAtomicNum() == 6 for a in mol.GetAtoms())
    n_sp3 = sum(
        a.GetAtomicNum() == 6 and a.GetHybridization() == Chem.HybridizationType.SP3
        for a in mol.GetAtoms()
    )
    if n_c == 0:
        return min(L, 12)
    sp3_frac = n_sp3 / n_c
    if sp3_frac < 0.10:
        return 12
    return L


