@_register_energy
def _apply_sigma_star_correction(mol: Chem.Mol, L: int, homo: float, lumo: float, **kwargs: Any) -> tuple[float, float]:
    """Apply σ* LUMO correction for S/P=O groups (d-orbital participation)."""
    sigma_scale = 0.40 if L >= 3 else 1.0
    for _spattern, _sname, _sshift in _SIGMA_STAR_LUMO:
        if len(mol.GetSubstructMatches(_spattern)) > 0:
            lumo += _sshift * sigma_scale
    return homo, lumo


@_register_energy
def _apply_cross_conjugation_penalty(mol: Chem.Mol, L: int, homo: float, lumo: float, **kwargs: Any) -> tuple[float, float]:
    """Apply cross-conjugation penalty (+0.30 eV to LUMO)."""
    if _is_cross_conjugated(mol):
        return homo, lumo + 0.30
    return homo, lumo


def _detect_steric_crowding(mol: Chem.Mol) -> bool:
    """Detect steric crowding in pi-systems via purely topological rules."""
    ring_info = mol.GetRingInfo()
    atom_rings = ring_info.AtomRings()

    for atom in mol.GetAtoms():
        if atom.GetAtomicNum() != 6:
            continue
        if atom.GetHybridization() != Chem.HybridizationType.SP2:
            continue
        if not any(
            _is_conjugated_bond(mol, atom.GetIdx(), nb.GetIdx())
            for nb in atom.GetNeighbors()
        ):
            continue
        n_non_h = sum(1 for nb in atom.GetNeighbors() if nb.GetAtomicNum() != 1)
        if n_non_h > 2:
            return True
        idx = atom.GetIdx()
        for ring in atom_rings:
            if idx in ring and len(ring) < 5:
                return True
    return False


@_register_energy
def _apply_steric_crowding_penalty(mol: Chem.Mol, L: int, homo: float, lumo: float, **kwargs: Any) -> tuple[float, float]:
    """Apply steric crowding penalty (+0.30 eV to both HOMO and LUMO)."""
    if _detect_steric_crowding(mol):
        return homo + 0.3, lumo + 0.3
    return homo, lumo


def _evaluate_tom_single_conformer(
    mol: Chem.Mol, xyz_content: str | None = None,
    use_geometry_correction: bool = False,
) -> tuple[float, float]:
    """Evaluate TOM for a single conformer with optional geometry-dependent penalty."""
    L = _longest_conjugation_path(mol)
    L = max(L, 2)
    L = _topological_sanity_l(mol, L)

    for _, l_fn in _L_CORRECTIONS:
        L = l_fn(mol, L, xyz_content=xyz_content)

    if use_geometry_correction:
        L = _apply_geometry_correction(mol, L)

    homo, lumo = _compute_tom_base_energies(L)
    for _, e_fn in _ENERGY_CORRECTIONS:
        homo, lumo = e_fn(mol, L, homo, lumo)

    return homo, lumo


def predict_tom_orbitals(
    mol: Chem.Mol, use_geometry_correction: bool = False,
) -> tuple[float, float]:
    """Predict HOMO/LUMO using the Topological Orbital Model (TOM).

    The model estimates frontier orbital energies from:
        1. Longest conjugation path length (L)
        2. HOMO-LUMO gap from particle-in-a-box: ΔE ∝ 1/L²
        3. Heteroatom perturbations (electron-withdrawing/donating)
        4. Aromatic ring stabilization
        5. Wiener-index compactness adjustment
        6. σ* LUMO correction for S/P=O groups
        7. Phosphate HOMO correction
        8. Base offset calibrated to 45 electrolyte molecules from DFT.
        9. Cross-conjugation penalty
        10. Steric crowding penalty

    Uses Boltzmann-weighted averaging over the top 3 conformers to stabilise
    predictions for sterically hindered, flexible conjugated systems.

    Args:
        mol: RDKit molecule.
        use_geometry_correction: If True, generate a conformer and reduce
            effective L by 20% for each conjugated bond with >30° dihedral
            deviation from planarity.

    Returns:
        (homo_eV, lumo_eV)
    """
    conformers = _generate_multi_xyz(mol, n_conformers=3)
    if not conformers:
        return _evaluate_tom_single_conformer(
            mol, use_geometry_correction=use_geometry_correction,
        )

    top = conformers[:3]
    energies = [e for _, e in top]
    weights = _boltzmann_weights(energies)

    homo_vals: list[float] = []
    lumo_vals: list[float] = []
    for xyz, _ in top:
        h, l = _evaluate_tom_single_conformer(
            mol, xyz, use_geometry_correction=use_geometry_correction,
        )
        homo_vals.append(h)
        lumo_vals.append(l)

    homo_w = sum(w * h for w, h in zip(weights, homo_vals))
    lumo_w = sum(w * l for w, l in zip(weights, lumo_vals))

    # Sanity check: LUMO must be above HOMO for a physical gap.
    # If TOM returns an inverted gap (LUMO <= HOMO), swap and log a warning,
    # then apply a minimum gap penalty.
    if lumo_w <= homo_w:
        logger.warning(
            "TOM predicted non-physical gap: HOMO=%.3f, LUMO=%.3f. Swapping and "
            "applying minimum gap penalty.",
            homo_w, lumo_w,
        )
        # Swap to maintain physical ordering
        if lumo_w < homo_w:
            lumo_w, homo_w = homo_w, lumo_w
        # Ensure at least a minimum gap of 0.5 eV
        if lumo_w - homo_w < 0.5:
            mid = (homo_w + lumo_w) / 2.0
            homo_w = mid - 0.25
            lumo_w = mid + 0.25

    return homo_w, lumo_w


