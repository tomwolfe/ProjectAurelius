def load_calibration_fingerprints(
    path: str | None = None,
) -> CalibrationData:
    """Load orbital_calibration fingerprints from a JSON file.

    Returns a (fingerprints, smiles) pair.  Returns empty lists
    if the file cannot be found or parsed.
    """
    if path is None:
        path = _resolve_calibration_path()
    if path is None or not os.path.exists(path):
        logger.warning(
            "orbital_calibration.json not found — "
            "TOM confidence will be based on structural heuristics only."
        )
        return [], []

    fps: list[Chem.DataStructs.ExplicitBitVect] = []
    smiles: list[str] = []
    try:
        with open(path) as f:
            data = json.load(f)
        for entry in data:
            smi = entry.get("smiles", "")
            ctx = MoleculeContext.from_smiles(smi)
            if ctx is not None:
                fp = ctx.get_ecfp4()
                fps.append(fp)
                smiles.append(smi)
        logger.info("Loaded %d calibration fingerprints from %s", len(fps), path)
    except Exception as exc:
        logger.warning("Failed to load calibration set: %s", exc)
    return fps, smiles


def _build_li_solvation_xyz(
    mol: Chem.Mol,
    n_solvents: int = 4,
    coordination_distance: float = 2.0,
) -> str:
    """Build an XYZ string for a [Li(solvent)_n]+ coordination complex.

    Places n_solvents copies of the candidate molecule around a central
    Li+ ion at approximately coordination_distance Å. The Li+ is placed
    at the origin, and each solvent molecule is placed at a random
    direction on a sphere of radius coordination_distance, with the
    molecule's closest atom to Li+ placed at that distance.

    Args:
        mol: RDKit molecule (solvent/electrolyte candidate).
        n_solvents: Number of solvent molecules in the coordination shell.
        coordination_distance: Li–solvent atom distance in Å (default 2.0).

    Returns:
        XYZ-format string for the [Li(solvent)_n]+ complex.
    """
    mol = Chem.RWMol(mol)
    mol.UpdatePropertyCache()
    with contextlib.suppress(Exception):
        mol = Chem.AddHs(mol)

    n_atoms_solvent = mol.GetNumAtoms()
    total_atoms = 1 + n_solvents * n_atoms_solvent

    conf = Chem.Conformer(total_atoms)

    # Place Li+ at origin
    conf.SetAtomPosition(0, Chem.rdGeometry.Point3D(0.0, 0.0, 0.0))

    atom_offset = 1
    rng = random.Random(42)

    for s in range(n_solvents):
        # Random direction on sphere
        theta = rng.uniform(0, 2 * math.pi)
        phi = math.acos(max(-1.0, min(1.0, 2 * rng.uniform(-1, 1))))
        dx = coordination_distance * math.sin(phi) * math.cos(theta)
        dy = coordination_distance * math.sin(phi) * math.sin(theta)
        dz = coordination_distance * math.cos(phi)

        # If no conformer yet, generate one
        if mol.GetNumConformers() == 0:
            params = AllChem.ETKDGv3()
            params.randomSeed = 42 + s
            AllChem.EmbedMolecule(mol, params)
            AllChem.MMFFOptimizeMolecule(mol)

        # Find the closest atom in the solvent molecule to place near Li+
        closest_idx = 0
        min_dist = float("inf")
        for a_idx in range(n_atoms_solvent):
            pos = mol.GetConformer().GetAtomPosition(a_idx)
            d = math.sqrt(pos.x ** 2 + pos.y ** 2 + pos.z ** 2)
            if d < min_dist:
                min_dist = d
                closest_idx = a_idx
            params = AllChem.ETKDGv3()
            params.randomSeed = 42 + s
            AllChem.EmbedMolecule(mol, params)
            AllChem.MMFFOptimizeMolecule(mol)

        for a_idx in range(n_atoms_solvent):
            pos = mol.GetConformer().GetAtomPosition(a_idx)
            # Place solvent molecule so its closest atom is at coordination_distance from Li+
            if a_idx == closest_idx:
                sx = dx
                sy = dy
                sz = dz
            else:
                sx = dx + pos.x
                sy = dy + pos.y
                sz = dz + pos.z
            global_idx = atom_offset + s * n_atoms_solvent + a_idx
            conf.SetAtomPosition(global_idx, Chem.rdGeometry.Point3D(sx, sy, sz))

        atom_offset += n_atoms_solvent

    # Build XYZ string
    lines = [str(total_atoms), ""]
    lines.append("Li 0.0 0.0 0.0")
    atom_offset = 1
    for s in range(n_solvents):
        for a_idx in range(n_atoms_solvent):
            atom = mol.GetAtomWithIdx(a_idx)
            symb = atom.GetSymbol()
            pos = conf.GetAtomPosition(atom_offset)
            lines.append(f"{symb} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}")
            atom_offset += 1

    return "\n".join(lines)


def _build_li_plus_xyz() -> str:
    """Build XYZ string for a bare Li+ ion (single atom)."""
    return "1\n\nLi 0.0 0.0 0.0"


def _build_solvent_xyz(
    mol: Chem.Mol,
) -> str:
    """Build XYZ string for an isolated solvent molecule."""
    mol = Chem.RWMol(mol)
    mol.UpdatePropertyCache()
    with contextlib.suppress(Exception):
        mol = Chem.AddHs(mol)

    params = AllChem.ETKDGv3()
    params.randomSeed = 42
    result = AllChem.EmbedMolecule(mol, params)
    if result != 0:
        return _generate_xyz(mol)

    try:
        ff = AllChem.MMFFGetMoleculeForceField(mol, mmffVariant="MMFF94s")
        if ff is not None:
            ff.Minimize(maxIts=500)
        else:
            AllChem.UFFOptimizeMolecule(mol)
    except Exception:
        pass

    conf = mol.GetConformer()
    n_atoms = mol.GetNumAtoms()
    lines = [str(n_atoms), ""]
    for i in range(n_atoms):
        atom = mol.GetAtomWithIdx(i)
        symb = atom.GetSymbol()
        pos = conf.GetAtomPosition(i)
        lines.append(f"{symb} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}")
    return "\n".join(lines)


def evaluate_li_solvation_cluster(
    mol: Chem.Mol,
    n_solvents: int = 4,
    solvent_name: str = "ether",
) -> dict[str, float]:
    """Evaluate Li+ solvation binding energy using xTB quantum chemistry.

    Constructs a 3D coordination complex [Li(solvent)_n]+ and computes
    the quantum binding energy:
        ΔE_bind = E([Li(S)_n]+) - (E(Li+) + n * E(S))

    Args:
        mol: RDKit molecule (solvent/electrolyte candidate).
        n_solvents: Number of solvent molecules in the coordination shell (default 4).
        solvent_name: Implicit solvation model for xTB (default "ether").

    Returns:
        Dict with keys:
            - li_binding_energy_kcal: Binding energy in kcal/mol (negative = stable)
            - cluster_homo_eV: HOMO of the cluster
            - cluster_lumo_eV: LUMO of the cluster
    """
    if not _HAS_XTB:
        return {"li_binding_energy_kcal": 0.0, "cluster_homo_eV": 0.0, "cluster_lumo_eV": 0.0}

    xyz_complex = _build_li_solvation_xyz(mol, n_solvents=n_solvents)
    xyz_li = _build_li_plus_xyz()
    xyz_solvent = _build_solvent_xyz(mol)

    result_complex = _run_xtb(xyz_complex, solvent=solvent_name)
    result_li = _run_xtb(xyz_li, solvent=solvent_name)
    result_solvent = _run_xtb(xyz_solvent, solvent=solvent_name)

    if result_complex is None or result_li is None or result_solvent is None:
        return {"li_binding_energy_kcal": 0.0, "cluster_homo_eV": 0.0, "cluster_lumo_eV": 0.0}

    e_complex = result_complex.get("homo_eV", 0.0) + result_complex.get("lumo_eV", 0.0)
    e_li = result_li.get("homo_eV", 0.0) + result_li.get("lumo_eV", 0.0)
    e_solvent = result_solvent.get("homo_eV", 0.0) + result_solvent.get("lumo_eV", 0.0)

    # Convert eV/atom to kcal/mol (1 eV ≈ 23.06 kcal/mol)
    # The binding energy is the energy of the complex minus the sum of fragments
    # We use the HOMO+LUMO sum as a proxy for total electronic energy
    binding_energy_ev = e_complex - (e_li + n_solvents * e_solvent)
    binding_energy_kcal = binding_energy_ev * 23.06

    return {
        "li_binding_energy_kcal": round(binding_energy_kcal, 4),
        "cluster_homo_eV": result_complex.get("homo_eV", 0.0),
        "cluster_lumo_eV": result_complex.get("lumo_eV", 0.0),
    }


