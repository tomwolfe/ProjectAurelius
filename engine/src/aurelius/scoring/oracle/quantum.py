def _generate_xyz(mol: Chem.Mol) -> str:
    """Generate an XYZ string from a molecule with a 3D conformer."""
    from rdkit.Chem import AllChem

    mol = Chem.RWMol(mol)
    mol.UpdatePropertyCache()
    with contextlib.suppress(Exception):
        mol = Chem.AddHs(mol)

    params = AllChem.ETKDGv3()
    params.randomSeed = 42
    result = AllChem.EmbedMolecule(mol, params)
    if result != 0:
        return _generate_xyz_geometry_optimized(mol)

    with contextlib.suppress(Exception):
        AllChem.UFFOptimizeMolecule(mol, maxIters=250)

    conf = mol.GetConformer()
    n_atoms = mol.GetNumAtoms()
    lines = [str(n_atoms), ""]
    for i in range(n_atoms):
        atom = mol.GetAtomWithIdx(i)
        symb = atom.GetSymbol()
        pos = conf.GetAtomPosition(i)
        lines.append(f"{symb} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}")
    return "\n".join(lines)


def _generate_multi_xyz(
    mol: Chem.Mol,
    n_conformers: int = _N_CONFORMERS,
    random_seed: int = 42,
) -> list[tuple[str, float]]:
    """Generate multiple conformers with MMFF94s optimizations and energies.

    Uses ETKDGv3 with multiple random seeds to sample diverse conformer
    space. Each conformer is MMFF94s-optimized and its MMFF94s energy
    is returned. Falls back to UFF if MMFF94s fails for a conformer.

    Physical justification: A single conformer generated by ETKDGv3 can
    be a high-energy, non-physical geometry that leads to garbage xTB/TOM
    predictions. Boltzmann weighting over multiple conformers stabilises
    predictions by down-weighting high-energy conformers and avoiding
    false-positive narrow gaps from strained geometries.

    Returns:
        List of (xyz_string, force_field_energy_kcal) tuples, sorted by energy
        ascending (lowest energy first).
    """
    from rdkit.Chem import AllChem

    mol = Chem.RWMol(mol)
    mol.UpdatePropertyCache()
    with contextlib.suppress(Exception):
        mol = Chem.AddHs(mol)

    results: list[tuple[str, float]] = []

    for i in range(n_conformers):
        mol_copy = Chem.RWMol(mol)
        params = AllChem.ETKDGv3()
        params.randomSeed = random_seed + i * 7
        result = AllChem.EmbedMolecule(mol_copy, params)
        if result != 0:
            continue
        energy: float | None = None
        try:
            ff = AllChem.MMFFGetMoleculeForceField(mol_copy, mmffVariant="MMFF94s")
            if ff is not None:
                converged = ff.Minimize(maxIts=500)
                energy = ff.CalcEnergy()
            else:
                raise RuntimeError("MMFF94s force field creation failed")
        except Exception:
            try:
                ff = AllChem.UFFGetMoleculeForceField(mol_copy)
                if ff is not None:
                    converged = ff.Minimize(maxIts=500)
                    energy = ff.CalcEnergy()
            except Exception:
                continue

        if energy is None:
            continue

        conf = mol_copy.GetConformer()
        n_atoms = mol_copy.GetNumAtoms()
        lines = [str(n_atoms), ""]
        for j in range(n_atoms):
            atom = mol_copy.GetAtomWithIdx(j)
            symb = atom.GetSymbol()
            pos = conf.GetAtomPosition(j)
            lines.append(f"{symb} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}")
        xyz = "\n".join(lines)
        results.append((xyz, energy))

    results.sort(key=lambda x: x[1])
    return results


def _boltzmann_weights(
    energies: list[float],
    temperature: float = _BOLTZMANN_TEMP,
) -> list[float]:
    """Compute Boltzmann weights from UFF energies.

    Physical justification: The Boltzmann factor exp(-E/kT) gives the
    relative probability of each conformer at temperature T. Conformers
    with energy > 5 kcal/mol above the minimum have negligible weight
    (< 0.02% at 298K) and are effectively excluded.

    Args:
        energies: List of UFF energies in kcal/mol.
        temperature: Temperature in Kelvin (default 298.15 K).

    Returns:
        List of normalised Boltzmann weights summing to 1.0.
    """
    if not energies:
        return []
    e_min = min(energies)
    boltz = [
        math.exp(-(e - e_min) / (_R_GAS * temperature))
        for e in energies
    ]
    total = sum(boltz)
    if total <= 0.0:
        return [1.0 / len(energies)] * len(energies)
    return [w / total for w in boltz]


def _generate_xyz_geometry_optimized(mol: Chem.RWMol) -> str:
    """Fallback XYZ generation using distance geometry without ETKDG."""
    from rdkit.Chem import AllChem, rdDistGeom

    mol = Chem.RWMol(mol)
    mol.UpdatePropertyCache()
    with contextlib.suppress(Exception):
        mol = Chem.AddHs(mol)

    params = rdDistGeom.ETKDGv3()
    params.randomSeed = 42
    params.useRandomCoords = True
    result = AllChem.EmbedMolecule(mol, params)
    if result != 0:
        with contextlib.suppress(Exception):
            AllChem.EmbedMolecule(mol, rdDistGeom.ETKDGv3())

    with contextlib.suppress(Exception):
        AllChem.UFFOptimizeMolecule(mol, maxIters=200)

    conf = mol.GetConformer()
    n_atoms = mol.GetNumAtoms()
    lines = [str(n_atoms), ""]
    for i in range(n_atoms):
        atom = mol.GetAtomWithIdx(i)
        symb = atom.GetSymbol()
        pos = conf.GetAtomPosition(i)
        lines.append(f"{symb} {pos.x:.6f} {pos.y:.6f} {pos.z:.6f}")
    return "\n".join(lines)


