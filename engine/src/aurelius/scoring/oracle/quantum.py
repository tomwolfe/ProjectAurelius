# QuantumBackend — Abstract base for quantum chemistry backends
# ---------------------------------------------------------------------------


class QuantumBackend(ABC):
    """Abstract quantum chemistry backend.

    Implementations must provide an ``evaluate(mol)`` method that returns a
    dict with at minimum ``homo_eV``, ``lumo_eV``, ``dipole_D``, and
    ``quantum_confidence``.
    """

    @abstractmethod
    def evaluate(self, mol: Chem.Mol) -> dict[str, float]:
        ...

    @property
    @abstractmethod
    def method(self) -> str:
        ...

    @property
    @abstractmethod
    def n_calls(self) -> int:
        ...

    def clear_cache(self) -> None:
        """Clear any internal caches. Default no-op."""
        return

    def get_cache_size(self) -> int:
        """Number of cached entries. Default 0."""
        return 0


class XTBBackend(QuantumBackend):
    """xTB (GFN2-xTB) quantum chemistry backend.

    Evaluates frontier orbitals by running the xTB binary on an embedded 3D
    conformer. Uses Boltzmann-weighted multi-conformer averaging for robust
    predictions.

    Args:
        n_conformers: Number of conformers to generate (default 5).
        n_top_conformers: Number of top conformers for Boltzmann averaging (default 3).
        max_workers: Maximum parallel xTB processes (default 4).
        batcher: Optional shared ``BatchXTBRunner`` for batched execution.
        allow_fallback: If True, fall back to TOM when xTB is unavailable.
        solvent: Implicit solvation model (e.g. "ether"). When set,
            appends ``--alpb <solvent>`` to all xTB command lines.
    """

    def __init__(
        self,
        n_conformers: int = _N_CONFORMERS,
        n_top_conformers: int = _N_TOP_CONFORMERS,
        max_workers: int = 4,
        batcher: BatchXTBRunner | None = None,
        allow_fallback: bool = False,
        solvent: str | None = "ether",
    ) -> None:
        if not _HAS_XTB:
            raise EnvironmentError(
                "XTBBackend requires the xtb binary on PATH. "
                "Install via: brew install xtb or https://github.com/grimme-lab/xtb/releases. "
                "In Docker, xtb is installed as part of the build image."
            )
        self._n_conformers = n_conformers
        self._n_top_conformers = n_top_conformers
        self._max_workers = max_workers
        self._batcher = batcher
        self._cache: dict[str, dict[str, float]] = {}
        self._allow_fallback = allow_fallback
        self._n_calls = 0
        self._solvent = solvent

    @property
    def method(self) -> str:
        return "xTB (GFN2-xTB)"

    @property
    def n_calls(self) -> int:
        return self._n_calls

    def clear_cache(self) -> None:
        self._cache.clear()

    def get_cache_size(self) -> int:
        return len(self._cache)

    def _run_xtb_flat(
        self,
        conformers: list[tuple[str, float]],
        n_top: int,
    ) -> tuple[list[dict[str, float]], list[float]]:
        top = conformers[:n_top]
        results: list[dict[str, float]] = []
        energies: list[float] = []
        if self._batcher is not None:
            futures = [self._batcher.submit(xyz) for xyz, _ in top]
            for (xyz, uff_energy), future in zip(top, futures, strict=False):
                xtb_result = future.result()
                if xtb_result is not None:
                    results.append(xtb_result)
                    energies.append(uff_energy)
        else:
            for xyz, uff_energy in top:
                xtb_result = _run_xtb(xyz, solvent=self._solvent)
                if xtb_result is not None:
                    results.append(xtb_result)
                    energies.append(uff_energy)
        return results, energies

    @staticmethod
    def _boltzmann_average(xtb_results: list[dict[str, float]], energies: list[float]) -> dict[str, float]:
        import numpy as np
        weights = _boltzmann_weights(energies)
        homo_w = sum(w * r["homo_eV"] for w, r in zip(weights, xtb_results, strict=False))
        lumo_w = sum(w * r["lumo_eV"] for w, r in zip(weights, xtb_results, strict=False))
        dipole_w = sum(w * r.get("dipole_D", 0.0) for w, r in zip(weights, xtb_results, strict=False))
        homo_vals = [r["homo_eV"] for r in xtb_results]
        conformer_variance = float(np.std(homo_vals, ddof=1)) if len(homo_vals) > 1 else 0.0
        conf = "xtb_high" if conformer_variance < 0.15 else "xtb"
        return {
            "homo_eV": homo_w,
            "lumo_eV": lumo_w,
            "dipole_D": dipole_w,
            "conformer_variance": round(conformer_variance, 4),
            "quantum_confidence": conf,
            "confidence_score": 1.0,
        }

    def _evaluate_with_boltzmann(self, mol: Chem.Mol) -> dict[str, float]:
        conformers = _generate_multi_xyz(mol, n_conformers=self._n_conformers)
        if not conformers:
            result = _run_xtb(_generate_xyz(mol), solvent=self._solvent)
            if result is not None:
                self._n_calls += 1
                result["quantum_confidence"] = "xtb"
                result["confidence_score"] = 1.0
                return result
            msg = "xTB evaluation failed — no conformers could be generated or evaluated."
            raise EnvironmentError(msg)

        xtb_results, energies = self._run_xtb_flat(conformers, self._n_top_conformers)

        if not xtb_results:
            self._n_calls += 1
            result = _run_xtb(conformers[0][0], solvent=self._solvent)
            if result is not None:
                self._n_calls += 1
                result["quantum_confidence"] = "xtb"
                result["confidence_score"] = 1.0
                return result
            msg = "xTB evaluation failed — all conformer calculations returned no result."
            raise EnvironmentError(msg)

        self._n_calls += len(xtb_results)

        if len(xtb_results) == 1:
            result = dict(xtb_results[0])
            result["quantum_confidence"] = "xtb"
            result["confidence_score"] = 1.0
            return result

        return self._boltzmann_average(xtb_results, energies)

    def evaluate(self, mol: Chem.Mol) -> dict[str, float]:
        smiles = Chem.MolToSmiles(mol)
        if smiles in self._cache:
            return dict(self._cache[smiles])

        result = self._evaluate_with_boltzmann(mol)

        if result is not None and "quantum_confidence" in result:
            self._cache[smiles] = result
            return dict(result)

        msg = "xTB evaluation returned no result."
        raise EnvironmentError(msg)


class TOMBackend(QuantumBackend):
    """Topological Orbital Model (TOM) fallback backend.

    Uses the particle-in-a-box model for pi-electrons with heteroatom
    perturbations and a calibration-set Tanimoto confidence score.

    Parameters
    ----------
    calibration_fps : list[ExplicitBitVect] | None
        Pre-loaded calibration fingerprints.  If ``None`` the backend
        will attempt to load them from disk on first evaluation.
    calibration_smiles : list[str] | None
        Corresponding SMILES strings (same length as *calibration_fps*).
    calibration_path : str | None
        Path to ``orbital_calibration.json``.  Only used if
        *calibration_fps* is ``None``.
    """

    def __init__(
        self,
        calibration_fps: list[Chem.DataStructs.ExplicitBitVect] | None = None,
        calibration_smiles: list[str] | None = None,
        calibration_path: str | None = None,
        allow_fallback: bool = False,
    ) -> None:
        self._cache: dict[str, dict[str, float]] = {}
        self._allow_fallback = allow_fallback
        self._n_calls = 0
        self._calibration_fps: list[Chem.DataStructs.ExplicitBitVect] | None = calibration_fps
        self._calibration_smiles: list[str] | None = calibration_smiles
        self._calibration_path: str | None = calibration_path

    @property
    def method(self) -> str:
        return "TOM (Topological Orbital Model)"

    @property
    def n_calls(self) -> int:
        return self._n_calls

    def clear_cache(self) -> None:
        self._cache.clear()

    def get_cache_size(self) -> int:
        return len(self._cache)

    def _ensure_calibration_loaded(self) -> None:
        """Lazy-load calibration fingerprints if not already set."""
        if self._calibration_fps is not None:
            return
        fps, smiles = load_calibration_fingerprints(self._calibration_path)
        self._calibration_fps = fps
        self._calibration_smiles = smiles

    def _compute_max_tanimoto_to_calibration(self, mol: Chem.Mol) -> float:
        """Compute max Tanimoto similarity of *mol* to the calibration set."""
        self._ensure_calibration_loaded()
        if not self._calibration_fps:
            return 0.0
        fp = AllChem.GetMorganFingerprintAsBitVect(mol, radius=2, nBits=2048)
        sims = BulkTanimotoSimilarity(fp, self._calibration_fps)
        return float(max(sims))

    def evaluate(self, mol: Chem.Mol) -> dict[str, float]:
        smiles = Chem.MolToSmiles(mol)
        if smiles in self._cache:
            return dict(self._cache[smiles])

        self._n_calls += 1
        homo, lumo = predict_tom_orbitals(mol)
        L = _longest_conjugation_path(mol)
        n_rings = mol.GetRingInfo().NumRings()

        max_sim = self._compute_max_tanimoto_to_calibration(mol)
        if max_sim < 0.5:
            quantum_conf = "tom_low"
        elif L <= 8 and n_rings <= 2:
            quantum_conf = "tom_high"
        else:
            quantum_conf = "tom_low"

        result: dict[str, float] = {
            "homo_eV": homo,
            "lumo_eV": lumo,
            "dipole_D": 0.0,
            "conformer_variance": 0.0,
            "quantum_confidence": quantum_conf,
            "confidence_score": round(max_sim, 4),
        }
        self._cache[smiles] = result
        return dict(result)


def _resolve_backend(
    backend: QuantumBackend | None = None,
    use_xtb: bool = True,
    n_conformers: int = _N_CONFORMERS,
    n_top_conformers: int = _N_TOP_CONFORMERS,
    max_workers: int = 4,
    batcher: BatchXTBRunner | None = None,
    solvent: str | None = "ether",
) -> QuantumBackend:
    """Resolve a quantum backend from parameters.

    Args:
        backend: Explicit backend instance (takes precedence).
        use_xtb: Whether to attempt using xTB.
        n_conformers: Number of conformers to generate.
        n_top_conformers: Number of top conformers for averaging.
        max_workers: Max workers for xTB batch.
        batcher: Optional shared ``BatchXTBRunner`` for batched execution.
        solvent: Implicit solvation model (e.g. "ether").

    Returns:
        A ``QuantumBackend`` instance.
    """
    if backend is not None:
        return backend
    if use_xtb and _HAS_XTB:
        return XTBBackend(
            n_conformers=n_conformers,
            n_top_conformers=n_top_conformers,
            max_workers=max_workers,
            batcher=batcher,
            solvent=solvent,
        )
    return TOMBackend()


# ---------------------------------------------------------------------------
# QuantumOracle — Unified interface for xTB + TOM fallback
# ---------------------------------------------------------------------------


class QuantumOracle:
    """Quantum-chemical oracle for frontier orbital energies.

    Two-tier evaluation:
       1. xTB (GFN2-xTB) via subprocess — preferred, real QM
       2. Topological Orbital Model (TOM) — conjugation-aware fallback

    Uses a pluggable ``QuantumBackend``. If no backend is supplied, defaults
    to ``XTBBackend`` (if xTB binary is on PATH) or ``TOMBackend``.

    Results are cached by SMILES to avoid redundant computation.

    Args:
        backend: Explicit backend instance (takes precedence).
        use_xtb: Whether to attempt using xTB.
        n_conformers: Number of conformers to generate (default 5).
        n_top_conformers: Number of top conformers for Boltzmann averaging (default 3).
        max_workers: Maximum parallel xTB processes (default 4).
        batch_size: Batch size for xTB batcher (default 10).
        allow_fallback: If True, fall back to TOM when xTB is unavailable.
        flush_interval: Maximum seconds to wait before flushing batcher (default 5.0).
        solvent: Implicit solvation model (e.g. "ether"). When set,
            appends ``--alpb <solvent>`` to all xTB command lines.
    """

    def __init__(
        self,
        backend: QuantumBackend | None = None,
        use_xtb: bool = True,
        n_conformers: int = _N_CONFORMERS,
        n_top_conformers: int = _N_TOP_CONFORMERS,
        max_workers: int = 4,
        batch_size: int = 10,
        allow_fallback: bool = False,
        flush_interval: float = 5.0,
        solvent: str | None = "ether",
    ) -> None:
        self._batcher: BatchXTBRunner | None = None
        if use_xtb and _HAS_XTB:
            self._batcher = BatchXTBRunner(
                batch_size=batch_size,
                flush_interval=flush_interval,
                max_workers=max_workers,
                solvent=solvent,
            )
        self._backend = _resolve_backend(
            backend=backend,
            use_xtb=use_xtb,
            n_conformers=n_conformers,
            n_top_conformers=n_top_conformers,
            max_workers=max_workers,
            batcher=self._batcher,
            solvent=solvent,
        )
        self._cache: dict[str, dict[str, float]] = {}
        self._allow_fallback = allow_fallback

        if isinstance(self._backend, TOMBackend):
            logger.info("QuantumOracle: xTB binary not found — using TOM fallback.")
        else:
            logger.info("QuantumOracle: xTB backend ENABLED.")

    @property
    def method(self) -> str:
        return self._backend.method

    @property
    def n_quantum_calls(self) -> int:
        return self._backend.n_calls

    @property
    def backend(self) -> QuantumBackend:
        """Access the underlying backend instance."""
        return self._backend

    def evaluate(self, mol: Chem.Mol) -> dict[str, float]:
        smiles = Chem.MolToSmiles(mol)
        if smiles in self._cache:
            return dict(self._cache[smiles])

        result = self._backend.evaluate(mol)

        if isinstance(self._backend, XTBBackend):
            li_result = evaluate_li_solvation_cluster(mol)
            result["li_binding_energy_kcal"] = li_result.get("li_binding_energy_kcal", 0.0)
            result["cluster_homo_eV"] = li_result.get("cluster_homo_eV", 0.0)
            result["cluster_lumo_eV"] = li_result.get("cluster_lumo_eV", 0.0)

        self._cache[smiles] = result
        return dict(result)

    def clear_cache(self) -> None:
        self._cache.clear()
        self._backend.clear_cache()

    def get_cache_size(self) -> int:
        return len(self._cache)

    def flush_batcher(self) -> None:
        """Force-flush any pending xTB jobs in the batcher."""
        if self._batcher is not None:
            self._batcher.flush()

    @property
    def batcher_pending(self) -> int:
        """Number of xTB jobs still pending in the batcher queue."""
        return self._batcher.pending_count if self._batcher is not None else 0
